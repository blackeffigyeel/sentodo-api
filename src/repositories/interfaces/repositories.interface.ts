import type {
  Account,
  ApiKey,
  AuditLog,
  CostRecord,
  LedgerEntry,
  Profile,
  ServiceState,
  Transaction,
  TransactionStatus,
  TransactionType,
  VerificationCode,
} from '../../domain/entities.model';
import type { Kobo } from '../../utils/money.util';

/**
 * Repository contracts. Services depend on these abstractions only.
 * Implementations: `postgres/` (Prisma), `mongo/` (Mongoose) and `memory/` (tests).
 * Implementations throw domain errors (ConflictError, ConcurrencyConflictError) and let
 * everything else propagate.
 */

/** Fields a caller supplies when creating a record; ids and timestamps are generated by the store. */
export type NewProfile = Pick<Profile, 'type' | 'email' | 'phone' | 'passwordHash'> &
  Partial<Pick<Profile, 'firstName' | 'lastName' | 'businessName'>>;

export type ProfilePatch = Partial<
  Pick<Profile, 'emailVerifiedAt' | 'phoneVerifiedAt' | 'identityVerifiedAt' | 'status' | 'passwordHash' | 'bvnHash'>
>;

export interface ProfileRepository {
  create(data: NewProfile): Promise<Profile>;
  findById(id: string): Promise<Profile | null>;
  findByEmail(email: string): Promise<Profile | null>;
  findByPhone(phone: string): Promise<Profile | null>;
  update(id: string, patch: ProfilePatch): Promise<Profile>;
}

export interface NewAccount {
  accountNumber: string;
  profileId: string;
  name: string;
}

export interface AccountRepository {
  /** @throws {ConflictError} If the account number is already taken. */
  create(data: NewAccount): Promise<Account>;
  findById(id: string): Promise<Account | null>;
  findByAccountNumber(accountNumber: string): Promise<Account | null>;
  listByProfile(profileId: string): Promise<Account[]>;
  /**
   * Optimistic-locking write: sets the balance only if the stored version still equals
   * `expectedVersion`, and increments the version.
   * @throws {ConcurrencyConflictError} If another writer changed the account first.
   * @throws {NotFoundError} If the account does not exist.
   */
  updateBalance(id: string, expectedVersion: number, newBalance: Kobo): Promise<Account>;
}

export type NewTransaction = Pick<
  Transaction,
  'reference' | 'profileId' | 'accountId' | 'type' | 'amount' | 'fee' | 'discount' | 'totalDebit' | 'feeWaived'
> &
  Partial<
    Pick<
      Transaction,
      | 'status'
      | 'idempotencyKey'
      | 'counterpartyAccountId'
      | 'counterpartyName'
      | 'counterpartyBank'
      | 'provider'
      | 'narration'
      | 'metadata'
    >
  >;

export type TransactionPatch = Partial<
  Pick<Transaction, 'status' | 'providerReference' | 'failureReason' | 'counterpartyName' | 'metadata'>
>;

export interface TransactionQuery {
  profileId: string;
  accountId?: string;
  type?: TransactionType;
  status?: TransactionStatus;
  limit: number;
  /** Return only transactions created before this instant (cursor pagination). */
  before?: Date;
}

export interface TransactionRepository {
  /** @throws {ConflictError} If the (profile, idempotency key) pair already exists. */
  create(data: NewTransaction): Promise<Transaction>;
  findById(id: string): Promise<Transaction | null>;
  findByReference(reference: string): Promise<Transaction | null>;
  findByIdempotencyKey(profileId: string, key: string): Promise<Transaction | null>;
  update(id: string, patch: TransactionPatch): Promise<Transaction>;
  /**
   * Atomic compare-and-set on the status. Applies the change only if the current status is
   * one of `from`, and returns null otherwise. This makes settlement idempotent: a job that
   * runs twice cannot credit or refund twice.
   */
  transition(id: string, from: TransactionStatus[], to: TransactionStatus, patch?: TransactionPatch): Promise<Transaction | null>;
  list(query: TransactionQuery): Promise<Transaction[]>;
  /** Counts transfers that used a free allowance since `since` (failed transfers are excluded). */
  countFreeTransfersSince(profileId: string, since: Date): Promise<number>;
}

export type NewLedgerEntry = Omit<LedgerEntry, 'id' | 'createdAt'>;

export interface LedgerRepository {
  add(entries: NewLedgerEntry[]): Promise<LedgerEntry[]>;
  listByAccount(accountId: string, limit: number): Promise<LedgerEntry[]>;
}

export type NewApiKey = Pick<ApiKey, 'profileId' | 'name' | 'prefix' | 'keyHash' | 'allowedIps'>;

export interface ApiKeyRepository {
  create(data: NewApiKey): Promise<ApiKey>;
  findById(id: string): Promise<ApiKey | null>;
  findByHash(keyHash: string): Promise<ApiKey | null>;
  listByProfile(profileId: string): Promise<ApiKey[]>;
  update(id: string, patch: Partial<Pick<ApiKey, 'allowedIps' | 'status' | 'lastUsedAt' | 'revokedAt' | 'name'>>): Promise<ApiKey>;
}

export type NewCostRecord = Pick<CostRecord, 'type' | 'amount'> &
  Partial<Pick<CostRecord, 'profileId' | 'reference' | 'note'>>;

export interface CostRepository {
  add(data: NewCostRecord): Promise<CostRecord>;
  listByType(type: CostRecord['type'], limit: number): Promise<CostRecord[]>;
}

/** The repositories that take part in a database transaction. */
export interface TransactionalRepositories {
  accounts: AccountRepository;
  transactions: TransactionRepository;
  ledger: LedgerRepository;
  costs: CostRepository;
}

/**
 * Unit of work: runs several repository operations atomically. If the callback throws,
 * every write made through the supplied repositories is rolled back.
 */
export interface UnitOfWork {
  run<T>(work: (repositories: TransactionalRepositories) => Promise<T>): Promise<T>;
}

export type NewVerificationCode = Pick<VerificationCode, 'profileId' | 'channel' | 'codeHash' | 'expiresAt'>;

export interface VerificationCodeRepository {
  /** Replaces any outstanding code for the same profile and channel. */
  replace(data: NewVerificationCode): Promise<VerificationCode>;
  findActive(profileId: string, channel: VerificationCode['channel']): Promise<VerificationCode | null>;
  incrementAttempts(id: string): Promise<VerificationCode>;
  markConsumed(id: string): Promise<void>;
}

export interface AuditLogRepository {
  add(data: Omit<AuditLog, 'id' | 'createdAt'>): Promise<void>;
}

export interface ServiceStateRepository {
  list(): Promise<ServiceState[]>;
  upsert(state: Omit<ServiceState, 'updatedAt'>): Promise<ServiceState>;
}

/** Every repository the application needs, grouped for dependency injection. */
export interface Repositories {
  profiles: ProfileRepository;
  accounts: AccountRepository;
  transactions: TransactionRepository;
  ledger: LedgerRepository;
  apiKeys: ApiKeyRepository;
  costs: CostRepository;
  unitOfWork: UnitOfWork;
  verificationCodes: VerificationCodeRepository;
  auditLogs: AuditLogRepository;
  serviceStates: ServiceStateRepository;
}
